"""MagoAgent: the sessions of this Hermes on MagoAgent's island.

Generated by MagoAgent (Ajustes > Integrações > Hermes Agent); "Remover" there takes this folder away.
Each event is handed to `magoagent hook external` and forgotten: with the app closed nothing happens and
Hermes carries on. The plugin only watches: it sends what a session is doing (it started, a prompt came,
a tool runs, the turn ended), never the messages, and reads nothing back.
"""
import json
import os
import subprocess
import sys
import threading

MAGOAGENT = __MAGOAGENT_EXE__
_last_session = ""


def _send(event, session_id="", **fields):
    """Hands one event to the app, off the caller's thread."""
    global _last_session
    if session_id:
        _last_session = session_id
    payload = {"hook_event_name": event, "session_id": session_id or _last_session, "cwd": os.getcwd()}
    payload.update(fields)

    def run():
        try:
            # no console window on Windows; its own process group elsewhere
            options = {"creationflags": 0x08000000} if sys.platform == "win32" else {"start_new_session": True}
            child = subprocess.Popen(
                [MAGOAGENT, "hook", "external"],
                stdin=subprocess.PIPE,
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
                env=dict(os.environ, MAGOAGENT_ORIGIN="hermes"),
                **options,
            )
            child.communicate(json.dumps(payload).encode("utf-8"), timeout=3)
        except Exception:
            pass

    threading.Thread(target=run).start()


def _text(value, most=200):
    return value[:most] if isinstance(value, str) else ""


def register(ctx):
    def on_session_start(**kwargs):
        _send("SessionStart", _text(kwargs.get("session_id")))

    def pre_llm_call(**kwargs):
        _send("UserPromptSubmit", _text(kwargs.get("session_id")))

    def pre_tool_call(**kwargs):
        _send("PreToolUse", tool_name=_text(kwargs.get("tool_name")))

    def post_tool_call(**kwargs):
        _send("PostToolUse", tool_name=_text(kwargs.get("tool_name")))

    def pre_approval_request(**kwargs):
        # Hermes asks in its own window; the island only shows that it waits
        _send("Notification", message="O Hermes pede a sua aprovação: " + _text(kwargs.get("description"), 160) + "?")

    def on_session_end(**kwargs):
        # despite its name, Hermes calls this at the end of every turn
        failed = kwargs.get("failed") or not (kwargs.get("completed") or kwargs.get("interrupted"))
        _send("StopFailure" if failed else "Stop", _text(kwargs.get("session_id")))

    hooks = {
        "on_session_start": on_session_start,
        "pre_llm_call": pre_llm_call,
        "pre_tool_call": pre_tool_call,
        "post_tool_call": post_tool_call,
        "pre_approval_request": pre_approval_request,
        "on_session_end": on_session_end,
    }
    for name, hook in hooks.items():
        ctx.register_hook(name, hook)
